// CONFIGURATIONS
import "@/configs/leaflet.setup";
// NEXT.JS TYPES
import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
// INTERNATIONALIZATION (NEXT-INTL)
import { getMessages, getLocale } from "next-intl/server";
// FONTS CONSTANTS
import { canela, dahlia, neon } from "@/app/utils/constants/styles/fonts";
import "./globals.css";
import { cookies } from "next/headers";
import { GlobalProviders } from "./utils/providers";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const messages = await getMessages();
  const locale = await getLocale();

    // ---------------------------------------------------------------------------
  // Theme côté serveur
  // ---------------------------------------------------------------------------

  const cookieStore = await cookies();

  const themeCookie = cookieStore.get("theme")?.value;

  const initialTheme = themeCookie === "dark" ? "dark" : "light";

  return (
    <html
      lang={locale}
      className={`${dahlia.variable} ${canela.variable} ${neon.variable}`}
    >
                  <body cz-shortcut-listen="true">
        <GlobalProviders
          locale={locale}
          messages={messages}
          initialTheme={initialTheme}
        >
          {children}
          </GlobalProviders></body>
    </html>
  );
}
